"""變數與四種基本資料型態：字串、整數、浮點數、布林值。"""

# string
string_data = "Hello World!"
print(string_data)
print(type(string_data))

# integer
integer_data = 123 + 456
print(integer_data)
print(type(integer_data))

# float
float_data = 3.1415926
print(float_data)
print(type(float_data))

# boolean
bool_data = True
print(bool_data)
print(type(bool_data))

# 型態跟著值走，同一個變數可以換放別種資料
data = 5
print(type(data))
data = "five"
print(type(data))
